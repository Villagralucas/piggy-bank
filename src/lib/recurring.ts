import { createClient } from "@/lib/supabase/server";
import { isDemo } from "@/lib/demo-mode";
import { demoStore } from "@/lib/demo/store";
import type { RecurringTransaction } from "@/lib/types";

/** Current date/time as seen in Argentina (the server runs in UTC). */
export function argentinaNow() {
  return new Date(new Date().toLocaleString("en-US", { timeZone: "America/Argentina/Buenos_Aires" }));
}

/** "YYYY-MM" for a date, in local time. */
export function monthKey(d: Date) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
}

function addMonths(key: string, n: number) {
  const [y, m] = key.split("-").map(Number);
  return monthKey(new Date(y, m - 1 + n, 1));
}

/** The date a rule falls on in a given month, clamping day 31 to the month's last day. */
export function dueDate(key: string, day: number) {
  const [y, m] = key.split("-").map(Number);
  const last = new Date(y, m, 0).getDate();
  return `${key}-${String(Math.min(day, last)).padStart(2, "0")}`;
}

/**
 * Months (oldest first) a rule still owes, up to today. A rule created this
 * month owes this month once its day arrives; one not opened for a while
 * catches up on every month it missed (capped at 12).
 */
export function pendingMonths(rule: RecurringTransaction, today = new Date()) {
  const current = monthKey(today);
  const todayISO = `${current}-${String(today.getDate()).padStart(2, "0")}`;
  let next = rule.last_generated_month
    ? addMonths(rule.last_generated_month, 1)
    : monthKey(new Date(rule.created_at));
  const months: string[] = [];
  while (next <= current && months.length < 12) {
    if (dueDate(next, rule.day_of_month) <= todayISO) months.push(next);
    next = addMonths(next, 1);
  }
  return months;
}

/**
 * Creates the movements of every active fixed expense/income that is due.
 * Safe to call on every page load: each rule remembers the last month it
 * generated, and the database refuses the same rule twice on one date.
 * Does nothing (silently) if the table hasn't been created yet.
 */
export async function syncRecurring() {
  const today = argentinaNow();

  if (await isDemo()) {
    for (const rule of demoStore.getRecurring()) {
      if (!rule.active) continue;
      const months = pendingMonths(rule, today);
      for (const key of months) {
        demoStore.createTransaction({
          account_id: rule.account_id,
          category_id: rule.category_id,
          type: rule.type,
          amount: Number(rule.amount),
          description: rule.description,
          occurred_at: dueDate(key, rule.day_of_month),
          recurring_id: rule.id,
        });
      }
      if (months.length) demoStore.updateRecurring(rule.id, { last_generated_month: months.at(-1)! });
    }
    return;
  }

  const supabase = await createClient();
  const { data, error } = await supabase
    .from("recurring_transactions")
    .select("*")
    .eq("active", true);
  if (error || !data) return;

  for (const rule of data as RecurringTransaction[]) {
    const months = pendingMonths(rule, today);
    if (months.length === 0) continue;

    for (const key of months) {
      const { error: insertError } = await supabase.from("transactions").insert({
        user_id: rule.user_id,
        account_id: rule.account_id,
        category_id: rule.category_id,
        type: rule.type,
        amount: rule.amount,
        description: rule.description,
        occurred_at: dueDate(key, rule.day_of_month),
        recurring_id: rule.id,
      });
      // 23505 = already generated by a parallel request; anything else, retry next load.
      if (insertError && insertError.code !== "23505") return;
    }

    await supabase
      .from("recurring_transactions")
      .update({ last_generated_month: months.at(-1) })
      .eq("id", rule.id);
  }
}
